def text(key: str, language: Language) -> str:
    return TEXT[language][key]


def error_text(message: str, language: Language) -> str:
    normalized = message.casefold()
    if "chat history" in normalized:
        key = "error_history"
    elif "create a new chat" in normalized:
        key = "error_create"
    elif "load chat messages" in normalized:
        key = "error_messages"
    elif "rename chat" in normalized:
        key = "error_rename"
    elif "update chat" in normalized:
        key = "error_update"
    elif "delete chat" in normalized:
        key = "error_delete"
    elif "cannot reach" in normalized or "unavailable" in normalized:
        key = "error_connection"
    elif "invalid response" in normalized:
        key = "error_response"
    elif "agent could not produce" in normalized:
        key = "error_agent"
    elif "selected language" in normalized:
        key = "error_language_save"
    else:
        key = "error_generic"
    return text(key, language)